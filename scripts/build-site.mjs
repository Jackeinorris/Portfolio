function validatePosts(posts) {
  if (!Array.isArray(posts)) throw new Error("posts.json must contain an array.");
  const slugs = new Set();
  const markdown = new Map();
  for (const [index, post] of posts.entries()) {
    const fail = (message) => { throw new Error(`Post ${index + 1} (${post?.slug ?? "unknown"}): ${message}`); };
    if (!post || typeof post !== "object" || Array.isArray(post)) fail("must be an object.");
    if (typeof post.slug !== "string" || !/^[a-z0-9-]+$/.test(post.slug)) fail("invalid slug.");
    if (["index", "post"].includes(post.slug)) fail("reserved slug.");
    if (slugs.has(post.slug)) fail("duplicate slug.");
    slugs.add(post.slug);
    if (post.draft !== undefined && typeof post.draft !== "boolean") fail("draft must be a boolean.");
    // Drafts may have incomplete editorial content, but still need a safe, unique slug.
    if (post.draft) continue;
    for (const field of ["title", "excerpt"]) {
      if (typeof post[field] !== "string" || !post[field].trim()) fail(`${field} is required.`);
    }
    const date = typeof post.date === "string" && /^\d{4}-\d{2}-\d{2}$/.test(post.date)
      ? new Date(`${post.date}T12:00:00Z`) : null;
    if (!date || Number.isNaN(date.getTime()) || date.toISOString().slice(0, 10) !== post.date) fail("invalid date; use YYYY-MM-DD.");
    if (!Array.isArray(post.tags) || post.tags.some((tag) => typeof tag !== "string" || !tag.trim())) fail("tags must be an array of non-empty strings.");
    for (const field of ["coverImage", "coverAlt", "coverPosition", "videoUrl", "location"]) {
      if (post[field] !== undefined && typeof post[field] !== "string") fail(`${field} must be a string.`);
    }
    if (post.coverImage) {
      const image = path.resolve(ENSAIOS_DIR, post.coverImage);
      if (!image.startsWith(ROOT + path.sep) || !fs.existsSync(image) || !fs.statSync(image).isFile()) fail("coverImage must reference an existing site image.");
    }
    if (post.videoUrl && !/^https?:\/\/(?:www\.)?vimeo\.com\/\d+(?:[/?#].*)?$/.test(post.videoUrl)) fail("videoUrl must be a Vimeo video URL.");
    const file = path.join(POSTS_DIR, `${post.slug}.md`);
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) fail("missing markdown file.");
    markdown.set(post.slug, fs.readFileSync(file, "utf8"));
  }
  return markdown;
}

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function escapeAttr(value) {
  return escapeHtml(value);
}

function inlineEmphasis(value) {
  let out = escapeHtml(value);
  out = out.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  out = out.replace(/\*([^*]+)\*/g, "<em>$1</em>");
  return out;
}

function inlineMarkdown(value) {
  // Parse links before formatting so emphasis cannot alter URL attributes.
  const links = /\[([^\]\n]+)\]\((https?:\/\/[^\s)]+)\)/g;
  let output = "";
  let cursor = 0;
  for (const match of value.matchAll(links)) {
    output += inlineEmphasis(value.slice(cursor, match.index));
    output += `<a href="${escapeAttr(match[2])}">${inlineEmphasis(match[1])}</a>`;
    cursor = match.index + match[0].length;
  }
  return output + inlineEmphasis(value.slice(cursor));
}

function renderMarkdown(md) {
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  const html = [];
  let para = [];
  let quote = [];
  let list = null;

  function flushPara() {
    if (!para.length) return;
    html.push(`<p>${inlineMarkdown(para.join(" "))}</p>`);
    para = [];
  }

  function flushQuote() {
    if (!quote.length) return;
    html.push(`<blockquote><p>${inlineMarkdown(quote.join(" "))}</p></blockquote>`);
    quote = [];
  }

  function flushList() {
    if (!list) return;
    html.push(`<${list.type}>${list.items.map((item) => `<li>${inlineMarkdown(item)}</li>`).join("")}</${list.type}>`);
    list = null;
  }

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      flushPara();
      flushQuote();
      flushList();
      continue;
    }

    const unordered = trimmed.match(/^[-*]\s+(.+)$/);
    const ordered = trimmed.match(/^\d+\.\s+(.+)$/);
    if (unordered || ordered) {
      flushPara();
      flushQuote();
      const type = unordered ? "ul" : "ol";
      if (list && list.type !== type) flushList();
      if (!list) list = { type, items: [] };
      list.items.push(unordered?.[1] || ordered?.[1]);
      continue;
    }

    flushList();
    if (trimmed.startsWith(">")) {
      flushPara();
      quote.push(trimmed.replace(/^>\s?/, ""));
      continue;
    }

    flushQuote();
    if (trimmed === "---") {
      flushPara();
      html.push("<hr>");
    } else if (trimmed.startsWith("### ")) {
      flushPara();
      html.push(`<h3>${inlineMarkdown(trimmed.slice(4))}</h3>`);
    } else if (trimmed.startsWith("## ")) {
      flushPara();
      html.push(`<h2>${inlineMarkdown(trimmed.slice(3))}</h2>`);
    } else {
      para.push(trimmed);
    }
  }

  flushPara();
  flushQuote();
  flushList();
  return html.join("\n");
}

function formatDate(date) {
  return new Date(`${date}T12:00:00`).toLocaleDateString("pt-BR", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

function formatMonth(date) {
  return new Date(`${date}T12:00:00`).toLocaleDateString("pt-BR", {
    month: "long",
    year: "numeric",
  });
}

function readingTime(md) {
  const words = md.trim().split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 200));
}

