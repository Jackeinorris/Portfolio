function renderSitemap(posts) {
  const pages = [
    ...TOP_LEVEL_PAGES,
    ...fs.readdirSync(path.join(ROOT, "projects"))
      .filter((file) => file.endsWith(".html"))
      .sort()
      .map((file) => ({ loc: `/projects/${file.replace(/\.html$/, "")}`, priority: "0.7" })),
    ...posts.map((post) => ({ loc: `/ensaios/${post.slug}`, lastmod: post.date, priority: "0.7" })),
  ];

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map((page) => `  <url>
    <loc>${SITE_URL}${page.loc}</loc>${page.lastmod ? `\n    <lastmod>${page.lastmod}</lastmod>` : ""}
    <priority>${page.priority}</priority>
  </url>`).join("\n")}
</urlset>
`;
}

function rssDate(date) {
  return new Date(`${date}T12:00:00Z`).toUTCString();
}

function renderFeed(posts, markdown) {
  const items = posts.map((post) => {
    const url = `${SITE_URL}/ensaios/${post.slug}`;
    const md = markdown.get(post.slug);
    const html = renderMarkdown(md).replace(/\]\]>/g, "]]&gt;");
    return `    <item>
      <title>${escapeHtml(post.title)}</title>
      <link>${url}</link>
      <guid isPermaLink="true">${url}</guid>
      <pubDate>${rssDate(post.date)}</pubDate>
      <description>${escapeHtml(post.excerpt)}</description>
      <content:encoded><![CDATA[${html}]]></content:encoded>
    </item>`;
  }).join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
  <channel>
    <title>Ensaios — J. V. Dias</title>
    <link>${SITE_URL}/ensaios/</link>
    <atom:link href="${SITE_URL}/ensaios/feed.xml" rel="self" type="application/rss+xml"/>
    <description>Ensaios sobre cinema, direção visual, 3D e processo criativo por J. V. Dias.</description>
    <language>pt-BR</language>
    <lastBuildDate>${new Date().toUTCString()}</lastBuildDate>
${items}
  </channel>
</rss>
`;
}

function renderRobots() {
  return `User-agent: *
Allow: /

Sitemap: ${SITE_URL}/sitemap.xml
`;
}

function upsertCanonical(file, href) {
  const text = read(file);
  const newline = text.includes("\r\n") ? "\r\n" : "\n";
  const canonical = `<link rel="canonical" href="${escapeAttr(href)}">`;
  let found = false;
  const updated = text.replace(/<link\b[^>]*>/gi, (tag) => {
    const rel = tag.match(/\srel\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i);
    if (!rel || !(rel[1] ?? rel[2] ?? rel[3]).toLowerCase().split(/\s+/).includes("canonical")) return tag;
    if (found) return "";
    found = true;
    return canonical;
  });
  if (found) return updated;
  if (!/<\/head\s*>/i.test(text)) throw new Error(`Cannot inject canonical into ${file}: closing head tag not found.`);
  return text.replace(/<\/head\s*>/i, `  ${canonical}${newline}</head>`);
}

function isGeneratedEssay(text, slug) {
  if (text.includes(GENERATED_ESSAY)) return true;
  // Recognize pre-marker build output without deleting arbitrary HTML in ensaios/.
  if (!text.includes('<main class="ensaio-page" id="conteudo">') || !text.includes('class="ensaio-signature"')) return false;
  const data = text.match(/<script type="application\/ld\+json" id="structured-data">([\s\S]*?)<\/script>/);
  if (!data) return false;
  try {
    return JSON.parse(data[1])["@graph"]?.some((node) =>
      node["@type"] === "BlogPosting" && new URL(node["@id"]).pathname === `/ensaios/${slug}`
    ) ?? false;
  } catch {
    return false;
  }
}

const posts = JSON.parse(read("ensaios/posts/posts.json"));
const markdown = validatePosts(posts);
const published = posts
  .filter((post) => !post.draft)
  .sort((a, b) => new Date(b.date) - new Date(a.date));

// Prepare every output before writing: content/template errors leave the last build intact.
const outputs = new Map([["ensaios/index.html", renderEssayIndex(published)]]);
for (const [index, post] of published.entries()) {
  outputs.set(`ensaios/${post.slug}.html`, renderStaticPost(post, index, published, markdown.get(post.slug)));
}

outputs.set("sitemap.xml", renderSitemap(published));
outputs.set("ensaios/feed.xml", renderFeed(published, markdown));
outputs.set("robots.txt", renderRobots());

for (const page of TOP_LEVEL_PAGES) {
  if (page.file) outputs.set(page.file, upsertCanonical(page.file, `${SITE_URL}${page.loc}`));
}

for (const file of fs.readdirSync(path.join(ROOT, "projects")).filter((name) => name.endsWith(".html"))) {
  outputs.set(`projects/${file}`, upsertCanonical(`projects/${file}`, `${SITE_URL}/projects/${file.replace(/\.html$/, "")}`));
}

const obsolete = fs.readdirSync(ENSAIOS_DIR, { withFileTypes: true })
  .filter((entry) => entry.isFile() && /^[a-z0-9-]+\.html$/.test(entry.name) && !["index.html", "post.html"].includes(entry.name))
  .map((entry) => `ensaios/${entry.name}`)
  .filter((file) => !outputs.has(file) && isGeneratedEssay(read(file), path.basename(file, ".html")));

for (const [file, text] of outputs) write(file, text);
// Only direct, recognized generated essay files are eligible for removal.
for (const file of obsolete) fs.unlinkSync(path.join(ROOT, file));

console.log(`Built ${published.length} essay pages, feed.xml, sitemap.xml, and robots.txt. Removed ${obsolete.length} obsolete essay pages.`);
